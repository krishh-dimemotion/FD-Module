DROP TABLE IF EXISTS FD_TAX_EVENTS;
DROP TABLE IF EXISTS FD_TAX_YEARS;
DROP TABLE IF EXISTS FD_ACCOUNT_ROLES;
DROP TABLE IF EXISTS FD_TRANSACTIONS;
DROP TABLE IF EXISTS FD_ACCOUNTS;
DROP TABLE IF EXISTS FD_BUSINESS_CLOCK;
CREATE TABLE FD_BUSINESS_CLOCK (FDBC_ENTITY_CD VARCHAR(10) PRIMARY KEY,FDBC_BUSINESS_DT DATE);
CREATE TABLE FD_ACCOUNTS (
 FDA_ID CHAR(36) PRIMARY KEY,FDA_ACCT_NUM VARCHAR(20),CUST_ID VARCHAR(32),FDA_CUST_NAME_SNAP VARCHAR(255),
 FDA_PRD_CODE VARCHAR(20),FDA_PRD_NAME_SNAP VARCHAR(100),FDA_CCY_CD CHAR(3),FDA_CCY_DECIMALS INT,FDA_STS VARCHAR(20),
 FDA_OPEN_DT DATE,FDA_MAT_DT DATE,FDA_CLOSURE_DT DATE,FDA_PRINCIPAL_AMT DECIMAL(20,4),FDA_PRINCIPAL_BAL DECIMAL(20,4),
 FDA_ACCRUED_INT_AMT DECIMAL(20,4),FDA_MAT_AMT DECIMAL(20,4),FDA_TAX_ENABLED BOOLEAN);
CREATE TABLE FD_ACCOUNT_ROLES (FDA_ID CHAR(36),CUST_ID VARCHAR(32),FDRL_ROLE_TYP VARCHAR(30));
CREATE TABLE FD_TRANSACTIONS (
 FDT_ID BIGINT PRIMARY KEY,FDA_ID CHAR(36),FDT_TXN_TYP VARCHAR(20),FDT_DR_CR CHAR(1),FDT_AMT DECIMAL(20,4),
 FDT_BAL_BEFORE DECIMAL(20,4),FDT_BAL_AFTER DECIMAL(20,4),FDT_TXN_DT DATE,FDT_PAN_SNAP VARCHAR(10),FDT_TDS_RT DECIMAL(6,4),FDT_REMARKS VARCHAR(255));

CREATE TABLE FD_TAX_YEARS (TAX_KEY VARCHAR(128) PRIMARY KEY,FY_START INT);
CREATE TABLE FD_TAX_EVENTS (SOURCE_FDT_ID BIGINT PRIMARY KEY,TAX_FDT_ID BIGINT,TAX_KEY VARCHAR(128),POLICY_VERSION VARCHAR(64),TAXABLE_AMOUNT DECIMAL(20,4));
