-- Read-only, per-currency reconciliation for legacy and tax-enabled accounts.
SELECT CASE WHEN NOT EXISTS (
 SELECT 1 FROM FD_GL_ENTRIES e JOIN FD_GL_ACCOUNTS g ON g.FDGL_CD=e.FDGE_GL_CD
 GROUP BY e.FDGE_TXN_GRP_ID,g.FDGL_CCY_CD
 HAVING SUM(CASE WHEN e.FDGE_DR_CR='D' THEN e.FDGE_AMT ELSE -e.FDGE_AMT END)<>0
) THEN 'PASS balanced GL groups by currency' ELSE 'FAIL unbalanced GL groups' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT c.currency FROM (SELECT FDA_CCY_CD currency FROM FD_ACCOUNTS UNION SELECT FDGL_CCY_CD FROM FD_GL_ACCOUNTS) c
 WHERE (SELECT COALESCE(SUM(FDA_PRINCIPAL_BAL),0) FROM FD_ACCOUNTS WHERE FDA_CCY_CD=c.currency)<>
 (SELECT COALESCE(SUM(FDGL_CURRENT_BAL),0) FROM FD_GL_ACCOUNTS WHERE FDGL_CCY_CD=c.currency AND (FDGL_CD='FD_DEP_LIAB' OR FDGL_CD LIKE 'FD_DEP_LIAB\_%'))
) THEN 'PASS deposit liability by currency' ELSE 'FAIL deposit liability' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT c.currency FROM (SELECT FDA_CCY_CD currency FROM FD_ACCOUNTS UNION SELECT FDGL_CCY_CD FROM FD_GL_ACCOUNTS) c
 WHERE (SELECT COALESCE(SUM(ROUND(FDA_ACCRUED_INT_AMT,FDA_CCY_DECIMALS)),0) FROM FD_ACCOUNTS WHERE FDA_STS='ACTIVE' AND FDA_CCY_CD=c.currency)<>
 (SELECT COALESCE(SUM(FDGL_CURRENT_BAL),0) FROM FD_GL_ACCOUNTS WHERE FDGL_CCY_CD=c.currency AND (FDGL_CD='FD_INT_PAYABLE' OR FDGL_CD LIKE 'FD_INT_PAYABLE\_%'))
) THEN 'PASS accrued liability by currency' ELSE 'FAIL accrued liability' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT 1 FROM FD_ACCOUNTS a WHERE a.FDA_PRINCIPAL_BAL <>
 (SELECT COALESCE(SUM(t.FDT_BAL_AFTER-t.FDT_BAL_BEFORE),0) FROM FD_TRANSACTIONS t WHERE t.FDA_ID=a.FDA_ID)
) THEN 'PASS account ledger balances' ELSE 'FAIL account ledger balances' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT 1 FROM FD_ACCOUNTS a WHERE a.FDA_STS IN ('CLOSED','MATURED_CLOSED','MATURED_RENEWED')
 AND (a.FDA_PRINCIPAL_BAL<>0 OR a.FDA_ACCRUED_INT_AMT<>0)
) THEN 'PASS closed balances' ELSE 'FAIL closed balances' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT 1 FROM FD_ACCOUNTS a WHERE a.FDA_RENEWED_FROM_ID IS NOT NULL AND
 (SELECT COUNT(*) FROM FD_ACCOUNT_ROLES r WHERE r.FDA_ID=a.FDA_ID) <>
 (SELECT COUNT(*) FROM FD_ACCOUNT_ROLES r WHERE r.FDA_ID=a.FDA_RENEWED_FROM_ID)
) THEN 'PASS copied role counts' ELSE 'FAIL copied role counts' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT g.FDGL_CCY_CD FROM FD_GL_ACCOUNTS g WHERE (g.FDGL_CD='FD_TAX_PAYABLE' OR g.FDGL_CD LIKE 'FD_TAX_PAYABLE\_%')
 GROUP BY g.FDGL_CCY_CD HAVING SUM(g.FDGL_CURRENT_BAL)<>
 (SELECT COALESCE(SUM(CASE WHEN t.FDT_DR_CR='D' THEN t.FDT_AMT ELSE -t.FDT_AMT END),0)
  FROM FD_TRANSACTIONS t WHERE t.FDT_TXN_TYP='TDS' AND t.FDT_CCY_CD=g.FDGL_CCY_CD)
) THEN 'PASS withholding payable by currency' ELSE 'FAIL withholding payable' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT y.TAX_KEY FROM FD_TAX_YEARS y WHERE y.TAX_WITHHELD <>
 (SELECT COALESCE(SUM(e.DEDUCTION),0) FROM FD_TAX_EVENTS e WHERE e.TAX_KEY=y.TAX_KEY)
) THEN 'PASS tax assessments' ELSE 'FAIL tax assessments' END;
