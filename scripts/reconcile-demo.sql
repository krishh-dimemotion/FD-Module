-- Read-only checks. The synthetic demo uses INR only, matching the configured GL currency.
SELECT CASE WHEN NOT EXISTS (
 SELECT 1 FROM FD_GL_ENTRIES GROUP BY FDGE_TXN_GRP_ID
 HAVING SUM(CASE WHEN FDGE_DR_CR='D' THEN FDGE_AMT ELSE -FDGE_AMT END) <> 0
) THEN 'PASS balanced GL groups' ELSE 'FAIL unbalanced GL groups' END;
SELECT CASE WHEN
 (SELECT COALESCE(SUM(FDA_PRINCIPAL_BAL),0) FROM FD_ACCOUNTS) =
 (SELECT FDGL_CURRENT_BAL FROM FD_GL_ACCOUNTS WHERE FDGL_CD='FD_DEP_LIAB')
 THEN 'PASS deposit liability' ELSE 'FAIL deposit liability' END;
SELECT CASE WHEN
 (SELECT COALESCE(SUM(ROUND(FDA_ACCRUED_INT_AMT,FDA_CCY_DECIMALS)),0) FROM FD_ACCOUNTS WHERE FDA_STS='ACTIVE') =
 (SELECT FDGL_CURRENT_BAL FROM FD_GL_ACCOUNTS WHERE FDGL_CD='FD_INT_PAYABLE')
 THEN 'PASS accrued liability' ELSE 'FAIL accrued liability' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT 1 FROM FD_ACCOUNTS a WHERE a.FDA_PRINCIPAL_BAL <>
 (SELECT COALESCE(SUM(t.FDT_BAL_AFTER-t.FDT_BAL_BEFORE),0) FROM FD_TRANSACTIONS t WHERE t.FDA_ID=a.FDA_ID)
) THEN 'PASS account ledger balances' ELSE 'FAIL account ledger balances' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT 1 FROM FD_ACCOUNTS a WHERE a.FDA_STS IN ('CLOSED','MATURED_CLOSED','MATURED_RENEWED')
 AND (a.FDA_PRINCIPAL_BAL<>0 OR a.FDA_ACCRUED_INT_AMT<>0)
) THEN 'PASS closed balances' ELSE 'FAIL closed balances' END;
SELECT CASE WHEN NOT EXISTS (
 SELECT 1 FROM FD_ACCOUNTS a WHERE a.FDA_RENEWED_FROM_ID IS NOT NULL AND
 (SELECT COUNT(*) FROM FD_ACCOUNT_ROLES r WHERE r.FDA_ID=a.FDA_ID) <>
 (SELECT COUNT(*) FROM FD_ACCOUNT_ROLES r WHERE r.FDA_ID=a.FDA_RENEWED_FROM_ID)
) THEN 'PASS copied role counts' ELSE 'FAIL copied role counts' END;
